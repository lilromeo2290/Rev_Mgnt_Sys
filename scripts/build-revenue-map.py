# User said: Revenue=1000000, Taxes=1100000 - but the first code here is 1100000
# So the mapping is: descriptions[0]='Revenue' has no code (it's a header), descriptions[1]='Taxes'→1100000
# OR the codes map starting from index 0
# Let's just zip them positionally as user requested

lines = ['export const REVENUE_CODE_MAP: { description: string; code: string }[] = [']
for i, desc in enumerate(descriptions):
    code = codes[i] if i < len(codes) else ''
    desc_esc = desc.replace("'", "\\'")
    lines.append(f"  {{ description: '{desc_esc}', code: '{code}' }},")
lines.append('];')
lines.append('')
lines.append('export const DESCRIPTION_TO_CODE: Record<string, string> = {};')
lines.append('export const CODE_TO_DESCRIPTION: Record<string, string> = {};')
lines.append('for (const m of REVENUE_CODE_MAP) {')
lines.append('  if (m.code) DESCRIPTION_TO_CODE[m.description] = m.code;')
lines.append('  if (m.code) CODE_TO_DESCRIPTION[m.code] = m.description;')
lines.append('}')

